USE_LEMMATIZATION = True

try:
    import pymorphy3
    _morph = pymorphy3.MorphAnalyzer()
except ImportError:
    USE_LEMMATIZATION = False
    _morph = None
    print("[Normalizer] pymorphy3 не установлен — работаем без лемматизации")

_TOKEN_RE = re.compile(r"[a-zA-Zа-яА-ЯёЁ0-9]+(?:[.,][0-9]+)?", re.UNICODE)


@lru_cache(maxsize=100_000)
def _lemmatize(token: str) -> str:
    """Кэшированная лемматизация (важно для скорости на 500 чанках)."""
    if not USE_LEMMATIZATION or _morph is None:
        return token
    
    return _morph.parse(token)[0].normal_form


def tokenize(text: str) -> list[str]:
    """
    Текст → список нормализованных токенов.
    - lowercase
    - выкидываем стоп-слова
    - лемматизируем (если включено)
    - числа сохраняем как есть (14,0 → "14,0")
    """
    if not text:
        return []
    tokens = []
    for tok in _TOKEN_RE.findall(text.lower()):
        # Чисто числовые токены оставляем без изменений
        if tok[0].isdigit():
            tokens.append(tok)
            continue
        if tok in STOPWORDS or len(tok) < 2:
            continue
        tokens.append(_lemmatize(tok))
    return tokens